// Builds workers/rollup/worker.js (one plain JavaScript file) from workers/rollup/index.ts, so the rollup Worker can be
// pasted into the Cloudflare dashboard without any tools (docs/ADMIN-SETUP.md). `--check` fails when the file is stale.
import { build } from 'esbuild';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join(import.meta.dirname, '..', '..', 'workers', 'rollup');
const OUT = join(DIR, 'worker.js');
const result = await build({
  entryPoints: [join(DIR, 'index.ts')],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: false,
  legalComments: 'none',
  write: false,
});
const code = `// GENERATED by \`npm run rollup:bundle\` from workers/rollup/index.ts. Do not edit by hand.\n${result.outputFiles[0].text}`;
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== code) {
    console.error('rollup-bundle: workers/rollup/worker.js is out of date. Run `npm run rollup:bundle`.');
    process.exit(1);
  }
  console.log('rollup-bundle: ok');
} else {
  writeFileSync(OUT, code, 'utf8');
  console.log('rollup-bundle: wrote workers/rollup/worker.js');
}
